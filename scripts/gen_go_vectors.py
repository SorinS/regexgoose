#!/usr/bin/env python3
"""Extract Go's regexp test data into test/vectors/, so nothing is hand-copied.

  * test/vectors/go_syntax.txt and go_regexp.txt: the unexported test tables
    of $GOROOT/src/regexp/syntax/*_test.go and $GOROOT/src/regexp/*_test.go
    (parseTests, foldcaseTests, literalTests, matchnlTests, nomatchnlTests,
    invalidRegexps, onlyPerl, onlyPOSIX, stringTests, simplifyTests,
    compileTests; findTests, goodRe, badRe, replaceTests,
    replaceLiteralTests, replaceFuncTests, metaTests, literalPrefixTests,
    subexpCases, splitTests, onePassTests, onePassTests1). Each package is
    copied to a temporary directory with tools/govectors/*_dump_test.go
    beside its tests, and `go test -run TestZZDump` writes the tables.
  * test/vectors/re2-search.txt, basic.dat, nullsubexpr.dat,
    repetition.dat: $GOROOT/src/regexp/testdata, copied byte for byte.
  * re2-exhaustive.txt.bz2 is not copied (428 KB, 61 MB unpacked);
    scripts/re2_exhaustive.py reads it from $GOROOT.

    python3 scripts/gen_go_vectors.py [--go PATH]
"""

import argparse
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), ".."))
VECTORS = os.path.join(ROOT, "test", "vectors")
TESTDATA = ["re2-search.txt", "basic.dat", "nullsubexpr.dat", "repetition.dat"]


def dump(go, goroot, pkg, module, dumper, out):
    src = os.path.join(goroot, "src", *pkg.split("/"))
    with tempfile.TemporaryDirectory() as tmp:
        for f in os.listdir(src):
            if not f.endswith(".go"):
                continue
            text = open(os.path.join(src, f), encoding="utf-8").read()
            if f.endswith("_test.go") and ('"internal/' in text or f in ("exec2_test.go",)):
                continue    # exec_test.go (internal/testenv) and exec2_test.go (uses it): no tables we use
            shutil.copy(os.path.join(src, f), tmp)
        shutil.copy(os.path.join(ROOT, "tools", "govectors", dumper), os.path.join(tmp, "zz_dump_test.go"))
        with open(os.path.join(tmp, "go.mod"), "w") as f:
            f.write("module %s\n\ngo 1.27\n" % module)
        env = dict(os.environ, VECTORS_OUT=out, GOPROXY="off", GOFLAGS="-mod=mod")
        p = subprocess.run([go, "test", "-count=1", "-run", "^TestZZDump$", "."], cwd=tmp, env=env,
                           capture_output=True, text=True)
        if p.returncode != 0:
            sys.exit("go test in a copy of %s failed:\n%s%s" % (pkg, p.stdout, p.stderr))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--go", default=shutil.which("go") or "go")
    args = ap.parse_args()
    goroot = subprocess.run([args.go, "env", "GOROOT"], capture_output=True, text=True, check=True).stdout.strip()
    version = subprocess.run([args.go, "env", "GOVERSION"], capture_output=True, text=True, check=True).stdout.strip()
    os.makedirs(VECTORS, exist_ok=True)
    for pkg, module, dumper, name in [("regexp/syntax", "gosyntax", "syntax_dump_test.go", "go_syntax.txt"),
                                      ("regexp", "goregexp", "regexp_dump_test.go", "go_regexp.txt")]:
        out = os.path.join(VECTORS, name)
        dump(args.go, goroot, pkg, module, dumper, out)
        body = open(out, encoding="latin-1").read()
        with open(out, "w", encoding="latin-1") as f:
            f.write("# Generated by scripts/gen_go_vectors.py from %s's %s tests; do not edit.\n" % (version, pkg))
            f.write(body)
        print("wrote", os.path.relpath(out, ROOT), body.count("\n"), "cases")
    for name in TESTDATA:
        shutil.copy(os.path.join(goroot, "src", "regexp", "testdata", name), os.path.join(VECTORS, name))
        print("copied", name)


if __name__ == "__main__":
    main()
